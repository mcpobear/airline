// Generates src/data/landMask.ts: a 0.5-degree land/ocean bitmap sampled from
// Natural Earth 110m land polygons (public domain, via the `world-atlas` package).
// Run with: npm run generate:landmask   (the output is committed; this is only
// needed if the resolution or source data changes).
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'
import { geoContains } from 'd3-geo'

const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'))
const land = feature(topo, topo.objects.land)

const W = 720
const H = 360
const bits = new Uint8Array(Math.ceil((W * H) / 8))

for (let y = 0; y < H; y++) {
  const lat = 90 - ((y + 0.5) * 180) / H
  for (let x = 0; x < W; x++) {
    const lon = -180 + ((x + 0.5) * 360) / W
    if (geoContains(land, [lon, lat])) {
      const idx = y * W + x
      bits[idx >> 3] |= 1 << (idx & 7)
    }
  }
}

const b64 = Buffer.from(bits).toString('base64')
const out = `// GENERATED by scripts/generate-landmask.mjs - do not edit by hand.
// Source: Natural Earth 110m land (public domain) via world-atlas.
export const LAND_MASK_WIDTH = ${W}
export const LAND_MASK_HEIGHT = ${H}
export const LAND_MASK_B64 =
  '${b64}'
`
writeFileSync('src/data/landMask.ts', out)
console.log(`Wrote src/data/landMask.ts (${b64.length} base64 chars)`)
